export const HOSPITALS: Hospital[] = hospitalDefs.map((h) => {
  const city = getCityBySlug(h.city)!;
  const area = areaFor(h.city, h.area);
  const departments: HospitalDepartment[] = h.departments.map((name, i) => ({
    id: `d1111111-1111-1111-1111-${h.id.slice(-8)}${String(i).padStart(4, '0')}`,
    hospitalId: h.id,
    name,
    description: `${name} department at ${h.name}`,
  }));
  const facilities: HospitalFacility[] = h.facilities.map((name, i) => ({
    id: `f1111111-1111-1111-1111-${h.id.slice(-8)}${String(i).padStart(4, '0')}`,
    hospitalId: h.id,
    name,
  }));
  const doctors: HospitalDoctorLink[] = h.doctorIndexes.map((idx, i) => {
    const doctor = DOCTORS[idx];
    return {
      id: `hd111111-1111-1111-1111-${h.id.slice(-8)}${String(i).padStart(4, '0')}`,
      hospitalId: h.id,
      doctorId: doctor.id,
      departmentId: departments[i % departments.length]?.id ?? null,
      employmentType: i === 0 ? 'FULL_TIME' : 'VISITING',
      isPrimary: i === 0,
      department: departments[i % departments.length] ?? null,
      doctor,
    };
  });

  return {
    id: h.id,
    name: h.name,
    slug: h.slug,
    type: h.type,
    description: h.description,
    phone: h.phone,
    email: h.email,
    address: h.address,
    areaId: area.id,
    cityId: city.id,
    lat: null,
    lng: null,
    verificationStatus: 'APPROVED',
    avgRating: h.rating.toFixed(2),
    reviewCount: h.reviews,
    isActive: true,
    city,
    area,
    facilities,
    departments,
    doctors,
  };
});
